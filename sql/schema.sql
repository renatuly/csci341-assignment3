-- CSCI 341 Assignment 3 -- Research Conference and Paper Review Management System
-- PostgreSQL schema (tables + required constraints). Re-runnable: drops everything first.

DROP VIEW  IF EXISTS accepted_paper_schedule;
DROP TABLE IF EXISTS review, paper_version, paper_author, paper_keyword, paper,
                     conference_session, track, conference_reviewer, conference_host,
                     conference, reviewer_expertise, reviewer, author_research_area,
                     author, app_user CASCADE;

-- ---------------------------------------------------------------- users
CREATE TABLE app_user (
    user_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    given_name    VARCHAR(60)  NOT NULL,
    surname       VARCHAR(60)  NOT NULL,
    email         VARCHAR(120) NOT NULL,
    affiliation   VARCHAR(150) NOT NULL,
    country       VARCHAR(60)  NOT NULL,
    phone_number  VARCHAR(30)  NOT NULL,
    CONSTRAINT uq_app_user_email UNIQUE (email)
);

-- Author subclass (shared primary key with app_user)
CREATE TABLE author (
    author_id  INTEGER PRIMARY KEY
               REFERENCES app_user (user_id) ON DELETE CASCADE,
    orcid      VARCHAR(19) UNIQUE
               CHECK (orcid IS NULL OR orcid ~ '^[0-9]{4}-[0-9]{4}-[0-9]{4}-[0-9]{3}[0-9X]$')
);

-- Multivalued attribute: research-area labels of an author
CREATE TABLE author_research_area (
    author_id   INTEGER      NOT NULL REFERENCES author (author_id) ON DELETE CASCADE,
    area_label  VARCHAR(100) NOT NULL,
    PRIMARY KEY (author_id, area_label)
);

-- Reviewer subclass (shared primary key with app_user)
CREATE TABLE reviewer (
    reviewer_id       INTEGER PRIMARY KEY
                      REFERENCES app_user (user_id) ON DELETE CASCADE,
    years_experience  INTEGER NOT NULL
                      CONSTRAINT ck_reviewer_experience CHECK (years_experience >= 0)
);

-- Multivalued attribute: expertise-area labels of a reviewer
CREATE TABLE reviewer_expertise (
    reviewer_id  INTEGER      NOT NULL REFERENCES reviewer (reviewer_id) ON DELETE CASCADE,
    area_label   VARCHAR(100) NOT NULL,
    PRIMARY KEY (reviewer_id, area_label)
);

-- ---------------------------------------------------------------- conferences
CREATE TABLE conference (
    conference_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                 VARCHAR(200) NOT NULL,
    acronym              VARCHAR(30)  NOT NULL,
    description          TEXT         NOT NULL,
    city                 VARCHAR(80)  NOT NULL,
    country              VARCHAR(60)  NOT NULL,
    start_date           DATE NOT NULL,
    end_date             DATE NOT NULL,
    submission_deadline  DATE NOT NULL,
    review_deadline      DATE NOT NULL,
    CONSTRAINT ck_conference_dates CHECK (end_date >= start_date)
);

-- Multivalued attribute: host institution names
CREATE TABLE conference_host (
    conference_id  INTEGER      NOT NULL REFERENCES conference (conference_id) ON DELETE CASCADE,
    host_name      VARCHAR(150) NOT NULL,
    PRIMARY KEY (conference_id, host_name)
);

-- M:N reviewer pool. Deleting a conference removes the pool membership only,
-- never the reviewer itself.
CREATE TABLE conference_reviewer (
    conference_id  INTEGER NOT NULL REFERENCES conference (conference_id) ON DELETE CASCADE,
    reviewer_id    INTEGER NOT NULL REFERENCES reviewer (reviewer_id)   ON DELETE CASCADE,
    PRIMARY KEY (conference_id, reviewer_id)
);

CREATE TABLE track (
    track_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conference_id   INTEGER      NOT NULL REFERENCES conference (conference_id) ON DELETE CASCADE,
    name            VARCHAR(150) NOT NULL,
    description     TEXT         NOT NULL,
    research_area   VARCHAR(100) NOT NULL,
    coordinator_id  INTEGER      NOT NULL REFERENCES reviewer (reviewer_id),
    CONSTRAINT uq_track_name UNIQUE (conference_id, name),
    -- optional rule: the coordinator belongs to the conference's reviewer pool
    CONSTRAINT fk_track_coordinator_pool FOREIGN KEY (conference_id, coordinator_id)
        REFERENCES conference_reviewer (conference_id, reviewer_id)
);

CREATE TABLE conference_session (
    session_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conference_id  INTEGER      NOT NULL REFERENCES conference (conference_id) ON DELETE CASCADE,
    title          VARCHAR(200) NOT NULL,
    session_date   DATE         NOT NULL,
    start_time     TIME         NOT NULL,
    end_time       TIME         NOT NULL,
    room_label     VARCHAR(60)  NOT NULL,
    chair_id       INTEGER      NOT NULL REFERENCES reviewer (reviewer_id),
    CONSTRAINT ck_session_times CHECK (end_time > start_time),
    -- optional rule: the chair belongs to the conference's reviewer pool
    CONSTRAINT fk_session_chair_pool FOREIGN KEY (conference_id, chair_id)
        REFERENCES conference_reviewer (conference_id, reviewer_id)
);

-- ---------------------------------------------------------------- papers
CREATE TABLE paper (
    paper_id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    track_id         INTEGER      NOT NULL REFERENCES track (track_id),   -- RESTRICT (default)
    title            VARCHAR(300) NOT NULL,
    abstract         TEXT         NOT NULL,
    submission_date  DATE         NOT NULL,
    status           VARCHAR(20)  NOT NULL DEFAULT 'submitted',
    session_id       INTEGER      REFERENCES conference_session (session_id) ON DELETE SET NULL,
    CONSTRAINT ck_paper_status CHECK
        (status IN ('submitted', 'under review', 'accepted', 'rejected', 'withdrawn')),
    -- part of application check 2, also guarded in the database
    CONSTRAINT ck_paper_session_accepted CHECK (session_id IS NULL OR status = 'accepted')
);

-- Multivalued attribute: keywords
CREATE TABLE paper_keyword (
    paper_id  INTEGER      NOT NULL REFERENCES paper (paper_id) ON DELETE CASCADE,
    keyword   VARCHAR(100) NOT NULL,
    PRIMARY KEY (paper_id, keyword)
);

-- M:N authorship with relationship attributes
CREATE TABLE paper_author (
    paper_id          INTEGER NOT NULL REFERENCES paper (paper_id)   ON DELETE CASCADE,
    author_id         INTEGER NOT NULL REFERENCES author (author_id), -- RESTRICT (default)
    author_position   INTEGER NOT NULL
                      CONSTRAINT ck_author_position CHECK (author_position > 0),
    is_corresponding  BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (paper_id, author_id),
    CONSTRAINT uq_paper_author_position UNIQUE (paper_id, author_position)
);
-- at most one corresponding author per paper (the app also requires at least one)
CREATE UNIQUE INDEX uq_paper_one_corresponding
    ON paper_author (paper_id) WHERE is_corresponding;

-- Weak entity: identified by (paper_id, version_no)
CREATE TABLE paper_version (
    paper_id       INTEGER      NOT NULL REFERENCES paper (paper_id) ON DELETE CASCADE,
    version_no     INTEGER      NOT NULL
                   CONSTRAINT ck_version_no CHECK (version_no > 0),
    file_location  VARCHAR(300) NOT NULL,
    uploaded_at    TIMESTAMP    NOT NULL,
    change_note    TEXT,
    PRIMARY KEY (paper_id, version_no)
);

-- Completed reviews only: every non-optional attribute is NOT NULL
CREATE TABLE review (
    review_id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paper_id                INTEGER     NOT NULL REFERENCES paper (paper_id) ON DELETE CASCADE,
    reviewer_id             INTEGER     NOT NULL REFERENCES reviewer (reviewer_id), -- RESTRICT
    overall_score           INTEGER     NOT NULL
                            CONSTRAINT ck_review_score CHECK (overall_score BETWEEN 1 AND 5),
    recommendation          VARCHAR(10) NOT NULL
                            CONSTRAINT ck_review_recommendation
                            CHECK (recommendation IN ('accept', 'reject')),
    comments_for_authors    TEXT        NOT NULL,
    confidential_comments   TEXT,
    review_submission_date  DATE        NOT NULL,
    CONSTRAINT uq_review_paper_reviewer UNIQUE (paper_id, reviewer_id)
);
